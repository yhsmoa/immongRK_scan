-- ============================================================
-- 상품관리 권장연령(rk_inventories.recommanded_age) 일괄 채움 — 2026-10-21 (immong-rocket 에 실행됨)
--
-- 이유몽(아동) 상품은 상품명 끝에 사이즈가 120 / 130 / 140 / 150 / 160 또는 110~120 처럼 적혀 있다.
-- 상품명에서 **마지막으로 나오는 독립된 숫자(110~160)** 를 사이즈로 보고 권장연령을 넣는다 (사용자 기준표):
--   120 → 5-7세 · 130 → 7-9세 · 140 → 9-11세 · 150 → 11-12세 · 160 → 12-14세
--   "110~120" 은 끝 숫자 120 → 5-7세. "120~130, 블루" 처럼 사이즈 뒤에 색이 와도 마지막 숫자(130)로 본다.
--   모델코드(E6H150 등) 안의 숫자는 \m\M(단어 경계) 때문에 잡히지 않는다.
-- 이미 값이 있는 행은 건드리지 않는다. 아이엠몽(성인) 상품은 대상이 아니다.
-- 라벨: 권장연령이 있으면 label-service 가 키즈 템플릿(사용연령 : {recommanded_age})을, 없으면 성인 템플릿을 고른다.
-- ============================================================

update public.rk_inventories i
   set recommanded_age = case (regexp_match(i.name, '^.*\m(1[1-6]0)\M'))[1]
                           when '120' then '5-7세'
                           when '130' then '7-9세'
                           when '140' then '9-11세'
                           when '150' then '11-12세'
                           when '160' then '12-14세'
                         end
 where i.name like '이유몽%'
   and nullif(trim(coalesce(i.recommanded_age, '')), '') is null
   and (regexp_match(i.name, '^.*\m(1[1-6]0)\M'))[1] in ('120', '130', '140', '150', '160');
