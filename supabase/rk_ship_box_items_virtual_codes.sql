-- ══════════════════════════════════════════════════════════════════
-- 출고 박스 행의 가상스캔 출처 (2026-10-15)
--   이 파일은 DB 에 적용된 정의의 사본이다 — 고칠 때는 여기와 DB 를 같이 고친다.
--
-- 왜
--   가상스캔은 입고분(입고코드별)과 재고분을 박스에 담지만 행에는 virtual_qty(개수)만 남아
--   어느 입고건(입고코드)의 물건인지 알 수 없었다. 대상 '전체' 로 입고코드를 여럿 골라 확정하면
--   한 박스에 여러 입고건이 섞이는데 화면·DB·모바일 입고 어디서도 구분이 안 됐다.
--
-- 규칙
--   virtual_codes = {"입고코드": n, …, "재고": n}  — virtual_qty 중 출처별 개수.
--   · 합 ≤ virtual_qty. 모자라는 만큼은 출처 미기록(이 컬럼 이전에 저장된 분량)이며
--     계산기(virtualPack)는 그 분량만 예전 가정("오래된 입고코드부터")으로 뺀다.
--   · 개수를 줄이면 재고 → 최신 입고코드 순으로 깎는다 (저장 서버와 화면이 같은 규칙).
--   · 모바일 입고 칩은 행의 입고코드와 같은 코드 분량(없으면 미기록 분량)만 그 행에 배정한다.
--   · 한 발주서(또는 라벨로 들어온 박스)에 입고코드가 둘 이상이면 모바일 입고 진입 전에 확인 모달을 띄운다.
-- ══════════════════════════════════════════════════════════════════

alter table public.rk_ship_box_items add column if not exists virtual_codes jsonb;
comment on column public.rk_ship_box_items.virtual_codes is
  '가상스캔 분량(virtual_qty)의 출처별 개수 {"입고코드": n, "재고": n}. 합 ≤ virtual_qty, 나머지는 출처 미기록(2026-10-15 이전 저장분).';
